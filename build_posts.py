#!/usr/bin/env python3
"""
Local Markdown-to-Blog builder for Dazaet Galicia's personal website.
Zero external dependencies (pure Python standard library).

Usage from your computer:
  1. Create or edit any .md file inside posts/
  2. Run: python build_posts.py
  3. Refresh your browser (or push to GitHub Pages / Cloudflare / Netlify).
"""
import html
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
POSTS_DIR = ROOT / "posts"
OUT_JS = ROOT / "data" / "blog-data.js"


def parse_frontmatter(text: str):
    meta = {}
    body = text
    m = re.match(r"^---\s*\r?\n(.*?)\r?\n---\s*\r?\n(.*)$", text, re.S)
    if m:
        raw_meta, body = m.group(1), m.group(2)
        for line in raw_meta.splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip()
    return meta, body.strip()


def inline_md(text: str) -> str:
    s = html.escape(text)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"\*([^*]+)\*", r"<em>\1</em>", s)
    s = re.sub(
        r"\[([^\]]+)\]\((https?://[^)]+)\)",
        r'<a href="\2" target="_blank" rel="noopener noreferrer">\1</a>',
        s,
    )
    return s


def md_to_html(md: str) -> str:
    lines = md.splitlines()
    out = []
    in_ul = False
    para = []

    def flush_para():
        if para:
            out.append("<p>" + inline_md(" ".join(para)) + "</p>")
            para.clear()

    def close_ul():
        nonlocal in_ul
        if in_ul:
            out.append("</ul>")
            in_ul = False

    for line in lines:
        s = line.strip()
        if not s:
            flush_para()
            close_ul()
            continue
        if s.startswith("### "):
            flush_para()
            close_ul()
            out.append(f"<h4>{inline_md(s[4:])}</h4>")
        elif s.startswith("## "):
            flush_para()
            close_ul()
            out.append(f"<h3>{inline_md(s[3:])}</h3>")
        elif s.startswith("- "):
            flush_para()
            if not in_ul:
                out.append("<ul>")
                in_ul = True
            out.append(f"<li>{inline_md(s[2:])}</li>")
        elif s.startswith("> "):
            flush_para()
            close_ul()
            out.append(f"<blockquote>{inline_md(s[2:])}</blockquote>")
        else:
            close_ul()
            para.append(s)

    flush_para()
    close_ul()
    return "\n".join(out)


def build():
    POSTS_DIR.mkdir(parents=True, exist_ok=True)
    posts = []
    for md_file in sorted(POSTS_DIR.glob("*.md"), reverse=True):
        raw = md_file.read_text(encoding="utf-8")
        meta, body = parse_frontmatter(raw)
        tags = [t.strip() for t in meta.get("tags", "").split(",") if t.strip()]
        posts.append(
            {
                "slug": meta.get("slug", md_file.stem),
                "date": meta.get("date", ""),
                "status": {
                    "en": meta.get("status", "Note"),
                    "es": meta.get("status_es", meta.get("status", "Nota")),
                },
                "type": {
                    "en": meta.get("type", "Reading Note"),
                    "es": meta.get("type_es", meta.get("type", "Nota de lectura")),
                },
                "title": {
                    "en": meta.get("title", md_file.stem),
                    "es": meta.get("title_es", meta.get("title", md_file.stem)),
                },
                "sourceAuthor": meta.get("source_author", ""),
                "sourceVenue": meta.get("source_venue", ""),
                "sourceUrl": meta.get("source_url", ""),
                "tags": tags,
                "summary": {
                    "en": meta.get("summary", ""),
                    "es": meta.get("summary_es", meta.get("summary", "")),
                },
                "bodyHtml": md_to_html(body),
                "file": f"posts/{md_file.name}",
            }
        )

    js = (
        "// Auto-generated by build_posts.py from posts/*.md\n"
        "// Edit Markdown files in posts/ and run `python build_posts.py`.\n"
        "window.BLOG_POSTS = "
        + json.dumps(posts, ensure_ascii=False, indent=2)
        + ";\n"
    )
    OUT_JS.parent.mkdir(parents=True, exist_ok=True)
    OUT_JS.write_text(js, encoding="utf-8")
    print(f"Built {len(posts)} post(s) -> {OUT_JS}")


if __name__ == "__main__":
    build()
